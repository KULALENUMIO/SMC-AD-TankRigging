// Makes the ground shaders for the track ruts (TankTrackRuts) in the project, from the project's own HDRP:
//   TankRig/GroundRuts  = HDRP/LitTessellation + ruts (meshes)
//   TankRig/TerrainRuts = HDRP/TerrainLit + tessellation + ruts (Unity Terrain)
// They are copies of HDRP's shaders with a few lines added, so they are generated here rather than shipped in this
// MIT package (HDRP's own code is under the Unity Companion License), and they always match the installed HDRP.
// Output: Assets/TankRig/Generated/Resources/TankRigRuts (Resources: they go into builds). Remade automatically when
// missing or when the HDRP version changes; by hand: Tools > SMC-AD > 戦車（Tank Rigging） > 轍の地面シェーダーを作る.
using System.IO;
using System.Linq;
using UnityEditor;
using UnityEngine;
using UnityEngine.Rendering.HighDefinition;

namespace TankRig.Editor
{
    [InitializeOnLoad]
    public static class TankRigRutsShaders
    {
        public const string OutDir = "Assets/TankRig/Generated/Resources/TankRigRuts";
        const string RutsHlsl = "Packages/com.smcad.tankrig/Runtime/Shaders/TankRigRuts.hlsl";
        const string HdrpPkg = "Packages/com.unity.render-pipelines.high-definition/";

        static TankRigRutsShaders() => EditorApplication.delayCall += () => { if (!UpToDate()) Generate(false); };

        static string HdrpVersion() => UnityEditor.PackageManager.PackageInfo.FindForAssembly(typeof(HDRenderPipeline).Assembly)?.version ?? "?";

        static bool UpToDate()
        {
            string stamp = Path.Combine(OutDir, "hdrp_version.txt");
            return File.Exists(Path.Combine(OutDir, "GroundRuts.shader")) && File.Exists(Path.Combine(OutDir, "TerrainRuts.shader"))
                && File.Exists(stamp) && File.ReadAllText(stamp).Trim() == HdrpVersion();
        }

        [MenuItem("Tools/SMC-AD/戦車（Tank Rigging）/轍の地面シェーダーを作る", priority = 63)]
        static void GenerateMenu() { Generate(true); }

        public static bool Generate(bool log)
        {
            var info = UnityEditor.PackageManager.PackageInfo.FindForAssembly(typeof(HDRenderPipeline).Assembly);
            if (info == null) { Debug.LogWarning("[TankRig] HDRP が見つからないので轍の地面シェーダーを作れません"); return false; }
            string hdrp = info.resolvedPath.Replace('\\', '/') + "/Runtime/Material/";
            string O = OutDir + "/";
            try
            {
                Directory.CreateDirectory(OutDir);
                string Read(string rel) => File.ReadAllText(hdrp + rel).Replace("\r\n", "\n");
                void Write(string name, string from, string text) => File.WriteAllText(O + name,
                    $"// GENERATED by com.smcad.tankrig (TankRigRutsShaders) from HDRP {info.version} {from} - do not edit; remade when HDRP changes\n" + text);
                string Rep(string s, string o, string n, int min = 1, int max = 1)
                {
                    int c = 0, i = 0;
                    while ((i = s.IndexOf(o, i, System.StringComparison.Ordinal)) >= 0) { c++; i += o.Length; }
                    if (c < min || c > max) throw new System.Exception($"HDRP {info.version}: expected {min}..{max} of '{o.Split('\n')[0]}', found {c}");
                    return s.Replace(o, n);
                }
                const string apply = "#if !defined(SHADER_STAGE_RAY_TRACING)\n    ApplyRutSurface(GetAbsolutePositionWS(posInput.positionWS), input.tangentToWorld[2], surfaceData);   // track ruts\n#endif\n";
                const string matUtil = "#include \"Packages/com.unity.render-pipelines.high-definition/Runtime/Material/MaterialUtilities.hlsl\"\n";

                // ---- meshes: HDRP/LitTessellation + ruts
                string LD = HdrpPkg + "Runtime/Material/Lit/LitData.hlsl", MM = HdrpPkg + "Runtime/Material/Lit/LitDataMeshModification.hlsl";
                var sh = Rep(Read("Lit/LitTessellation.shader"), "Shader \"HDRP/LitTessellation\"", "Shader \"TankRig/GroundRuts\"");
                sh = Rep(sh, LD, O + "GroundRutsData.hlsl", 5, 99);
                Write("GroundRuts.shader", "LitTessellation.shader", sh);
                var d = Rep(Read("Lit/LitData.hlsl"), matUtil, matUtil + $"#include \"{RutsHlsl}\"\n");
                d = Rep(d, "    // Use bent normal to sample GI if available\n", apply + "\n    // Use bent normal to sample GI if available\n");
                d = Rep(d, MM, O + "GroundRutsMeshMod.hlsl");
                Write("GroundRutsData.hlsl", "LitData.hlsl", d);
                var m = Rep(Read("Lit/LitDataMeshModification.hlsl"), "#endif // _TESSELLATION_DISPLACEMENT\n\n    return input;",
                    "#endif // _TESSELLATION_DISPLACEMENT\n\n    // track ruts: the ground moves straight down / up by the deformation field\n    input.positionRWS.y += RutHeight(GetAbsolutePositionWS(input.positionRWS).xz);\n\n    return input;");
                m = Rep(m, "float GetTessellationFactor(AttributesMesh input)\n{\n    return _TessellationFactor;\n}",
                    "float GetTessellationFactor(AttributesMesh input)\n{\n    // track ruts: full tessellation only near ruts, the rest of the ground stays as it is\n    float3 pAWS = GetAbsolutePositionWS(TransformObjectToWorld(input.positionOS));\n    return RutNear(pAWS.xz) > 0.5 ? _TessellationFactor : 1.0;\n}");
                Write("GroundRutsMeshMod.hlsl", "LitDataMeshModification.hlsl", m);

                // ---- Unity Terrain: HDRP/TerrainLit + tessellation + ruts
                string TT = HdrpPkg + "Runtime/Material/TerrainLit/TerrainLitTemplate.hlsl", TD = HdrpPkg + "Runtime/Material/TerrainLit/TerrainLitData.hlsl";
                var ts = Rep(Read("TerrainLit/TerrainLit.shader"), "Shader \"HDRP/TerrainLit\"", "Shader \"TankRig/TerrainRuts\"");
                var parts = ts.Split(new[] { "Name \"" }, System.StringSplitOptions.None);
                string[] tess = { "GBuffer", "ShadowCaster", "DepthOnly", "Forward" };   // the ground's shape (depth prepass and gbuffer must match)
                for (int i = 1; i < parts.Length; i++)
                {
                    string name = parts[i].Substring(0, parts[i].IndexOf('"'));
                    if (tess.Contains(name))
                        parts[i] = Rep(parts[i], "#pragma vertex Vert", "#pragma vertex Vert\n            #pragma hull Hull\n            #pragma domain Domain\n            #pragma require tessellation tessHW\n            #define TESSELLATION_ON");
                    parts[i] = parts[i].Replace(TT, O + "TerrainRutsTemplate.hlsl");
                }
                Write("TerrainRuts.shader", "TerrainLit.shader", string.Join("Name \"", parts));
                var tp = Rep(Read("TerrainLit/TerrainLitTemplate.hlsl"), TD, O + "TerrainRutsData.hlsl");
                const string common = "#include \"Packages/com.unity.render-pipelines.core/ShaderLibrary/Common.hlsl\"\n";
                tp = Rep(tp, common, common + "#ifdef TESSELLATION_ON\n#include \"Packages/com.unity.render-pipelines.core/ShaderLibrary/GeometricTools.hlsl\"\n#include \"Packages/com.unity.render-pipelines.core/ShaderLibrary/Tessellation.hlsl\"\n#endif\n");
                Write("TerrainRutsTemplate.hlsl", "TerrainLitTemplate.hlsl", tp);
                var td = Rep(Read("TerrainLit/TerrainLitData.hlsl"), matUtil, matUtil + $"#include \"{RutsHlsl}\"\n" +
                    "#ifdef TESSELLATION_ON\n// tessellation settings come from TankTrackRuts (globals: the terrain material has no such properties)\n#define HAVE_TESSELLATION_MODIFICATION\n" +
                    "float4 _RutTess;   // x factor near ruts, y full-tessellation distance, z no-tessellation distance, w target triangle size (px)\n" +
                    "#define _TessellationFactorMinDistance _RutTess.y\n#define _TessellationFactorMaxDistance _RutTess.z\n#define _TessellationFactorTriangleSize _RutTess.w\n" +
                    "#define _TessellationShapeFactor 0.0\n#define _TessellationBackFaceCullEpsilon -1.0\n#endif\n");
                td = Rep(td, "    float3 bentNormalWS = surfaceData.normalWS;\n", apply + "    float3 bentNormalWS = surfaceData.normalWS;\n");
                td += "\n#if defined(TESSELLATION_ON) && !defined(SHADER_STAGE_RAY_TRACING)\nfloat GetMaxDisplacement() { return _RutParams.x + 0.05; }\n\n" +
                      "// full tessellation only near ruts (vertex positions are already the terrain's here)\nfloat GetTessellationFactor(AttributesMesh input)\n{\n" +
                      "    float3 pAWS = GetAbsolutePositionWS(TransformObjectToWorld(input.positionOS));\n    return RutNear(pAWS.xz) > 0.5 ? _RutTess.x : 1.0;\n}\n\n" +
                      "// track ruts: the ground moves straight down / up by the deformation field\nVaryingsMeshToDS ApplyTessellationModification(VaryingsMeshToDS input, float3 timeParameters)\n{\n" +
                      "    input.positionRWS.y += RutHeight(GetAbsolutePositionWS(input.positionRWS).xz);\n    return input;\n}\n#endif\n";
                Write("TerrainRutsData.hlsl", "TerrainLitData.hlsl", td);

                File.WriteAllText(O + "hdrp_version.txt", info.version);
                AssetDatabase.Refresh();
                if (log) Debug.Log($"[TankRig] 轍の地面シェーダーを作りました（HDRP {info.version}）: {OutDir}");
                return true;
            }
            catch (System.Exception e)
            {
                Debug.LogWarning($"[TankRig] 轍の地面シェーダーを作れませんでした（この HDRP では轍は使えません）: {e.Message}");
                return false;
            }
        }
    }
}
